export const presetDialogueCount = Object.values(SCRIPTS).reduce(
  (sum, scripts) => sum + scripts.length,
  0,
);

/** Deterministic selection permits testing and rotates lines on repeat encounters. */
export function presetDialogueForEncounter(
  residentIds: [string, string],
  place: DialoguePlace,
  sequence: number,
): DialogueResult | null {
  if (residentIds[0] === residentIds[1] || !residentIds.every((id) => fictionalId.test(id)))
    return null;
  const scripts: readonly Script[] = SCRIPTS[place];
  const hash = [...residentIds.join("|")].reduce(
    (value, character) => value + character.charCodeAt(0),
    0,
  );
  const serial = Number.isFinite(sequence) ? Math.max(0, Math.trunc(sequence)) : 0;
  const selected = scripts[(hash + serial) % scripts.length];
  if (!selected) return null;
  return {
    schemaVersion: 1,
    requestId: `preset_${place}_${serial}`,
    source: "PRESET",
    safety: "PASSED",
    lines: selected.map((text, index) => ({
      residentId: residentIds[index % 2]!,
      text,
    })),
  };
}

/**
 * Uses reviewed local lines whenever live AI is disabled, unavailable or fails.
 * A disabled switch never starts a network request; stale async replies are discarded.
 */
export async function resolveEncounterDialogue({
  residentIds,
  place,
  sequence,
  allowLive,
  isActive,
  requestLive,
}: {
  residentIds: [string, string];
  place: DialoguePlace;
  sequence: number;
  allowLive: () => boolean;
  isActive: () => boolean;
  requestLive: () => Promise<DialogueResult>;
}): Promise<DialogueResult | null> {
  if (!isActive()) return null;
  const preset = () => presetDialogueForEncounter(residentIds, place, sequence);
  if (!allowLive()) return preset();
  try {
    const live = await requestLive();
    if (!isActive()) return null;
    return allowLive() && live.source === "LIVE" && live.safety === "PASSED" ? live : preset();
  } catch {
    return isActive() ? preset() : null;
  }
}
